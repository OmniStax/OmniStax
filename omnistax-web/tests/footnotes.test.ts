import { test } from 'node:test';
import assert from 'node:assert/strict';
import { noteExercise, placeNotes } from '../src/lib/content/fragment';
import { prerenderMath } from '../src/lib/math/prerender';
import { FigureSchema, FootnoteSchema, ServedExerciseSchema } from '../src/lib/content/schema';

test('placeNotes: markers become numbered links to notes that link back; the book keeps its numbers, corrections are bracketed and AI-marked', () => {
  const text = prerenderMath([
    '<p>A claim<sup class="fn" data-note="n3"></sup>.</p>',
    '<div class="equation" id="eq-1-21">$$S \\cdot L = J^2 \\tag{1.21}$$<sup class="fn" data-note="c-b"></sup></div>',
    '<p>A slip $3A/2$<sup class="fn" data-note="c-a"></sup> and a stray<sup class="fn" data-note="gone"></sup>.</p>',
  ].join(''), {});
  const rows = [
    { id: 'c-a', kind: 'correction', html: 'It is $2A$.' },
    { id: 'n3', kind: 'book', number: '3', html: 'The book’s own words.' },
    { id: 'c-b', kind: 'correction', html: 'A factor 2 is missing.' },
  ].map((r) => FootnoteSchema.parse(r));
  const { html, notes } = placeNotes(text, rows, '1.3', 'Generated by Claude Opus 5.5 · high effort');

  assert.match(html, /<sup class="fn book" id="1\.3-fnref-n3"><a href="#1\.3-fn-n3">3<\/a><\/sup>/);
  assert.match(html, /<\/span><sup class="fn correction" id="1\.3-fnref-c-b"><a href="#1\.3-fn-c-b">\[1\]<\/a><\/sup><\/div>/, 'a marker after a display equation survives the math pass and is numbered first');
  assert.match(html, /<sup class="fn correction" id="1\.3-fnref-c-a"><a href="#1\.3-fn-c-a">\[2\]<\/a><\/sup>/);
  assert.match(html, /<sup class="fn" data-note="gone"><\/sup>/, 'a marker that names no row is left for the checker');

  const [book, corrections] = notes.split('</section>');
  assert.match(book, /^<section class="notes" id="1\.3-section-notes"><h2>Notes<\/h2><ol><li class="book" id="1\.3-fn-n3"><a class="fn-back" href="#1\.3-fnref-n3">3<\/a><div class="fn-body">The book’s own words\.<\/div><\/li><\/ol>$/);
  assert.match(corrections, /^<section class="notes" id="1\.3-section-corrections"><h2>Corrections<\/h2>/);
  assert.deepEqual([...corrections.matchAll(/<li class="correction" id="1\.3-fn-([\w-]+)"><a class="fn-back" href="#1\.3-fnref-\1">\[(\d)\]<\/a><div class="fn-body">[^<]*<span class="ai-mark"[^>]*title="Generated by Claude Opus 5\.5 · high effort"[^>]*>.*?<\/span><\/div><\/li>/g)].map((m) => [m[1], m[2]]), [['c-b', '1'], ['c-a', '2']]);
  assert.ok(!book.includes('ai-mark'), 'the book’s footnotes are the book’s words and wear no mark');
  assert.deepEqual(placeNotes('<p>plain</p>', rows, '1.3'), { html: '<p>plain</p>', notes: '' }, 'a page with no markers prints no notes');
});

test('placeNotes: a marker inside a note is numbered after the text\'s, and a note\'s ids and links are qualified like the text\'s', () => {
  const rows = [
    { id: 'n1', kind: 'book', number: '1', html: '<p>By <a href="#eq-2-10">(2.10)</a>,</p><div class="equation" id="eq-4-7">x</div><sup class="fn" data-note="c-in"></sup>' },
    { id: 'c-in', kind: 'correction', html: 'In the note.' },
    { id: 'c-text', kind: 'correction', html: 'In the text.' },
  ].map((r) => FootnoteSchema.parse(r));
  const { notes } = placeNotes('<p>x<sup class="fn" data-note="n1"></sup><sup class="fn" data-note="c-text"></sup></p>', rows, '4.1');
  assert.match(notes, /<a href="#4\.1-eq-2-10">\(2\.10\)<\/a>,<\/p><div class="equation" id="4\.1-eq-4-7">/);
  assert.match(notes, /<sup class="fn correction" id="4\.1-fnref-c-in"><a href="#4\.1-fn-c-in">\[2\]<\/a><\/sup>/);
  assert.deepEqual([...notes.matchAll(/<li class="correction" id="4\.1-fn-([\w-]+)"><a class="fn-back" href="#4\.1-fnref-\1">\[(\d)\]/g)].map((m) => [m[1], m[2]]), [['c-text', '1'], ['c-in', '2']]);
});

test('noteExercise: a card numbers its own corrections in prompt, option and solution order and carries them AI-marked; placeNotes sets a caption correction after its figure, under its label', () => {
  const fn = (id: string): string => `<sup class="fn" data-note="${id}"></sup>`;
  const rows = [
    { id: 'c-sol', kind: 'correction', html: 'It is $3A$.' },
    { id: 'c-ex', kind: 'correction', html: 'Na<sub>2</sub>SO<sub>4</sub> is meant.' },
    { id: 'c-fig', kind: 'correction', html: '<p>Iron’s are 3<em>d</em>.</p>', figure: 'sim-spin' },
  ].map((r) => FootnoteSchema.parse(r));
  const ex = ServedExerciseSchema.parse({ id: 'e70', source_id: 'fs-1', kind: 'exercise', bloom: 'Apply', place: { at: 'end' }, prompt: `and NaSO<sub>4</sub>${fn('c-ex')}?`, answer: { type: 'choice', options: ['a', 'b'], correct: 0, solution: `$2A$${fn('c-sol')}` } });
  const noted = noteExercise(ex, rows, 'Generated by Claude Opus 5.5 · high effort');
  assert.equal(noted.prompt, 'and NaSO<sub>4</sub><sup class="fn correction">[1]</sup>?');
  assert.equal(noted.answer.solution, '$2A$<sup class="fn correction">[2]</sup>');
  assert.deepEqual(noted.corrections?.map((c) => [c.html.replace(/<span class="ai-mark"[^]*$/, ''), c.solution ?? false]), [['Na<sub>2</sub>SO<sub>4</sub> is meant.', false], ['It is $3A$.', true]], 'a note on the solution says so, for the card to hold it until the solution shows, and keeps its number');
  assert.ok(noted.corrections?.every((c) => /title="Generated by Claude Opus 5\.5 · high effort"/.test(c.html)));
  assert.equal(noteExercise({ ...ex, prompt: 'plain', answer: { ...ex.answer, solution: 's' } }, rows).corrections, undefined, 'a card with no marker carries no corrections');

  const figures = [{ id: 'sim-spin', kind: 'sim', number: '19.35', draws: [] }].map((f) => FigureSchema.parse(f));
  const { html, notes } = placeNotes(`<p>x${fn('c-ex')}</p><figure class="sim" id="19.3-sim-spin" data-figure="19.35"><div class="sim-head"></div></figure>`, rows, '19.3', undefined, figures);
  assert.match(html, /<div class="sim-head"><\/div><sup class="fn correction" id="19\.3-fnref-c-fig"><a href="#19\.3-fn-c-fig">\[2\]<\/a><\/sup><\/figure>$/, 'the caption’s marker waits at the figure’s end, numbered in the order it stands');
  assert.match(notes, /<li class="correction" id="19\.3-fn-c-fig"><a class="fn-back" href="#19\.3-sim-spin">\[2\]<\/a><div class="fn-body"><p><span class="eyebrow fn-figure">Figure 19\.35<\/span> Iron’s are 3<em>d<\/em>\.<span class="ai-mark"/, 'the note links back to the figure and reads under its label');
});
